export function getTranslation(lang: string, key: TranslationKey, vars?: Record<string, string>): string {
  const langTranslations = translations[lang] || translations['en'];
  let text = langTranslations[key] || translations['en'][key] || key;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      text = text.replace(`{${k}}`, v);
    });
  }
  return text;
}

export function detectBrowserLanguage(): string {
  const browserLang = navigator.language || 'en';
  // Try exact match first
  const exactMatch = LANGUAGES.find(l => l.code === browserLang);
  if (exactMatch) return exactMatch.code;
  // Try prefix match (e.g. "en-US" → "en")
  const prefix = browserLang.split('-')[0];
  const prefixMatch = LANGUAGES.find(l => l.code === prefix);
  if (prefixMatch) return prefixMatch.code;
  return 'en';
}
